void OLED_SendData(uint8_t data) {
    HAL_I2C_Mem_Write(&hi2c1, OLED_ADDR, 0x40, 1, &data, 1, 10);
}

void OLED_SetCursor(uint8_t page, uint8_t col) {
    OLED_SendCommand(0xB0 + page);             // 0~7 페이지 설정
    OLED_SendCommand(0x00 + (col & 0x0F));     // 하위 4비트 열 주소
    OLED_SendCommand(0x10 + (col >> 4));       // 상위 4비트 열 주소
}

void OLED_PrintChar(char c) {
    for (uint8_t i = 0; i < 8; i++) {
        OLED_SendData(Font8x8[(uint8_t)c][i]);
    }
}

void OLED_Printf(char* str) {
    while (*str) {
        OLED_PrintChar(*str++);
    }
}

void OLED_Clear(void) {
    uint8_t zero[128] = {0}; // 한 줄(Page)을 통째로 0으로 채움
    for (uint8_t i = 0; i < 8; i++) {
        OLED_SetCursor(i, 0);
        HAL_I2C_Mem_Write(&hi2c1, OLED_ADDR, 0x40, 1, zero, 128, 100);
    }
}
